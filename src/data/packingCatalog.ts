export const PACKING_CATALOG: PackingCatalogItem[] = Object.entries(RAW).flatMap(([categoryId, entries]) =>
  entries.map((entry) => {
    const sep = entry.indexOf('|')
    const name = (sep === -1 ? entry : entry.slice(0, sep)).trim()
    const keywords = sep === -1 ? undefined : entry.slice(sep + 1).replace(/\|/g, ' ').trim()
    return { id: `${categoryId}:${slug(name)}`, name, categoryId, keywords }
  })
)

export const getPackingCategory = (id: string): PackingCategory =>
  PACKING_CATEGORIES.find((c) => c.id === id) || PACKING_CATEGORIES[PACKING_CATEGORIES.length - 1]

const normalize = (s: string) =>
  s
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')

// Cerca per nome e sinonimi, ignorando accenti e maiuscole; ogni parola digitata deve comparire
export const searchPackingCatalog = (query: string, categoryId?: string | null): PackingCatalogItem[] => {
  const words = normalize(query).split(/\s+/).filter(Boolean)
  return PACKING_CATALOG.filter((item) => {
    if (categoryId && item.categoryId !== categoryId) return false
    if (words.length === 0) return true
    const haystack = normalize(`${item.name} ${item.keywords || ''}`)
    return words.every((w) => haystack.includes(w))
  })
}
